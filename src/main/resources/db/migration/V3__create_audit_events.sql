CREATE TABLE audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT NOT NULL,
    actor_username VARCHAR(255) NOT NULL,
    action VARCHAR(40) NOT NULL,
    resource_type VARCHAR(32) NOT NULL,
    resource_reference VARCHAR(255) NOT NULL,
    before_value VARCHAR(255),
    after_value VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT audit_events_action_ck CHECK (action IN (
        'BLACKLIST_IP_ADDED',
        'BLACKLIST_IP_REMOVED',
        'CARD_FLAGGED',
        'CARD_UNFLAGGED',
        'FEEDBACK_SUBMITTED',
        'LIMIT_UPDATED'
    )),
    CONSTRAINT audit_events_resource_type_ck CHECK (resource_type IN (
        'SUSPICIOUS_IP',
        'STOLEN_CARD',
        'TRANSACTION',
        'TRANSACTION_LIMITS'
    ))
);

COMMENT ON COLUMN audit_events.actor_id IS
    'User ID snapshot. Intentionally has no foreign key so user deletion cannot alter audit history.';

CREATE INDEX audit_events_created_idx
    ON audit_events (created_at DESC, id DESC);

CREATE FUNCTION prevent_audit_event_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'audit_events is append-only';
END;
$$;

CREATE TRIGGER audit_events_append_only
    BEFORE UPDATE OR DELETE ON audit_events
    FOR EACH ROW
    EXECUTE FUNCTION prevent_audit_event_mutation();
