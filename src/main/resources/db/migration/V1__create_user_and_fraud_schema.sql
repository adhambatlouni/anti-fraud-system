CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    username VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    enabled BOOLEAN NOT NULL
);

CREATE UNIQUE INDEX users_username_lower_uq
    ON users (LOWER(username));

CREATE TABLE authorities (
    username VARCHAR(255) NOT NULL,
    authority VARCHAR(50) NOT NULL,
    CONSTRAINT authorities_user_fk
        FOREIGN KEY (username) REFERENCES users (username) ON DELETE CASCADE,
    CONSTRAINT authorities_username_authority_uq
        UNIQUE (username, authority)
);

CREATE TABLE suspicious_ips (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ip VARCHAR(15) NOT NULL UNIQUE
);

CREATE TABLE stolen_cards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number CHAR(16) NOT NULL UNIQUE
);

CREATE TABLE transaction_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount BIGINT NOT NULL,
    ip VARCHAR(15) NOT NULL,
    number CHAR(16) NOT NULL,
    region VARCHAR(4) NOT NULL,
    transaction_date TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    result VARCHAR(32) NOT NULL,
    feedback VARCHAR(32) NOT NULL DEFAULT '',
    CONSTRAINT transaction_history_amount_positive_ck
        CHECK (amount > 0),
    CONSTRAINT transaction_history_region_ck
        CHECK (region IN ('EAP', 'ECA', 'HIC', 'LAC', 'MENA', 'SA', 'SSA')),
    CONSTRAINT transaction_history_result_ck
        CHECK (result IN ('ALLOWED', 'MANUAL_PROCESSING', 'PROHIBITED')),
    CONSTRAINT transaction_history_feedback_ck
        CHECK (feedback IN ('', 'ALLOWED', 'MANUAL_PROCESSING', 'PROHIBITED'))
);

CREATE TABLE transaction_limits (
    id SMALLINT PRIMARY KEY,
    max_allowed BIGINT NOT NULL,
    max_manual BIGINT NOT NULL,
    CONSTRAINT transaction_limits_single_row_ck
        CHECK (id = 1),
    CONSTRAINT transaction_limits_allowed_positive_ck
        CHECK (max_allowed > 0),
    CONSTRAINT transaction_limits_manual_positive_ck
        CHECK (max_manual > 0)
);

